GH = 10
LINE = 12


def g(*rows: str, top: int = 1) -> list[str]:
    """Rows start at `top`; the rest of the 10 rows are blank."""
    w = max(len(r) for r in rows)
    out = ['.' * w] * top + [r.ljust(w, '.') for r in rows]
    return out + ['.' * w] * (GH - len(out))


