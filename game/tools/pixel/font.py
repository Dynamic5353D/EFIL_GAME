"""EFIL Pixel: our own proportional bitmap font, so text stays pixel-sharp at the native 480x270.

Each glyph is 10 rows: row 0 is headroom, capitals sit on rows 1-7 (baseline under row 7), lowercase
x-height is rows 3-7, descenders use rows 8-9. Glyphs are white; the game tints them.
Exported as an AngelCode BMFont (XML) atlas that Phaser's BitmapText reads.
"""
