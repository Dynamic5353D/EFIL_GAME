def build() -> tuple[Canvas, str]:
    chars = list(G.items())
    x, y, row_h = 0, 0, GH + 1
    width = 256
    rects = []
    for ch, rows in chars:
        w = len(rows[0])
        if x + w + 1 > width:
            x, y = 0, y + row_h
        rects.append((ch, x, y, w))
        x += w + 1
    c = Canvas(width, y + row_h)
    white = (255, 255, 255, 255)
    for (ch, x, y, w) in rects:
        for ry, row in enumerate(G[ch]):
            for rx, px_ in enumerate(row):
                if px_ == '#':
                    c.set(x + rx, y + ry, white)
    lines = [
        '<?xml version="1.0"?>',
        '<font>',
        f'  <info face="EFIL Pixel" size="{GH}" bold="0" italic="0" />',
        f'  <common lineHeight="{LINE}" base="8" scaleW="{c.w}" scaleH="{c.h}" pages="1" />',
        '  <pages><page id="0" file="font.png" /></pages>',
        f'  <chars count="{len(rects)}">',
    ]
    for (ch, x, y, w) in rects:
        adv = w + 1 if ch != ' ' else 3
        lines.append(f'    <char id="{ord(ch)}" x="{x}" y="{y}" width="{w}" height="{GH}" xoffset="0" yoffset="0" xadvance="{adv}" page="0" />')
    lines += ['  </chars>', '</font>']
    return c, '\n'.join(lines)
